// The Woz Monitor expects a small KBD/RESET vector at $FFFC/D and
// a BRK vector pointing to $FF00.
const WOZ_RESET_LO = 0x00, WOZ_RESET_HI = 0xFF; // PC starts at $FF00
const WOZ_IRQ_LO = 0x00, WOZ_IRQ_HI = 0xFF;
const WOZ_NMI_LO = 0xFA; // NMI doesn't make sense for Apple 1 but provide
const WOZ_NMI_HI = 0xFA;

// ----- Apple 1 I/O hooks -----
// $D010: write displays a character (with high bit cleared)
// $D011: read returns key (high bit set when no key pressed)
const IO_DSP = 0xD010; // display output
const IO_KBD = 0xD011; // keyboard input

function installApple1IO(cpu, onDisplay, getKey) {
  cpu.ioOutput = (addr, val) => {
    if (addr === IO_DSP) onDisplay(val & 0x7F);
  };
  cpu.ioInput = (addr) => {
    if (addr === IO_KBD) {
      const k = getKey();
      return k < 0 ? 0x80 : (k | 0x80); // original Apple 1: high bit set
    }
    return 0;
  };
}

function loadWozMonitor(cpu) {
  for (let i = 0; i < WOZ_ROM.length; i++) {
    cpu.mem[0xFF00 + i] = WOZ_ROM[i];
  }
  // Vectors
  cpu.mem[0xFFFC] = WOZ_RESET_LO;
  cpu.mem[0xFFFD] = WOZ_RESET_HI;
  cpu.mem[0xFFFE] = WOZ_IRQ_LO;
  cpu.mem[0xFFFF] = WOZ_IRQ_HI;
  cpu.mem[0xFFFA] = WOZ_NMI_LO;
  cpu.mem[0xFFFB] = WOZ_NMI_HI;
}

if (typeof window !== 'undefined') {
  window.WOZ_ROM = WOZ_ROM;
  window.installApple1IO = installApple1IO;
  window.loadWozMonitor = loadWozMonitor;
  window.IO_DSP = IO_DSP;
  window.IO_KBD = IO_KBD;
}
