/* ============================================================
   Apple 1: Woz Monitor + I/O
   ============================================================
   The Woz Monitor is a 256-byte ROM that Steve Wozniak wrote for
   the Apple 1. It provides a tiny "front panel" interface:
     - After reset, prints "\" prompt and waits for input.
     - "0: 12 34 ..." deposits bytes starting at $00.. (or
       wherever the user types in the address).
     - "0R" runs from the address 0 (or last deposit address).
     - "0. 12 34 ..." examines memory and prints bytes.
   The original ROM lives at $FF00-$FFFF on the Apple 1.

   The original Apple 1 used a "dumb terminal" interface: writing
   to $D010 displays a character; reading $D011 reads a key.
   We emulate that here, plus a small JavaScript implementation of
   the Woz Monitor for use when the user wants to talk to the
   "real" machine instead of running their own program.
   ============================================================ */

