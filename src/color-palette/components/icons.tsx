/**
 * Hand-rolled inline SVG icons (24x24, Lucide-style stroke geometry).
 *
 * - No external icon package: the app needs a small, fixed set, so we keep
 *   the bundle lean and the dependency tree minimal.
 * - All icons are decorative. They are paired with a visible text label or
 *   an `aria-label` on the controlling element, so `aria-hidden` is set on
 *   the <svg> by default (override via `aria-hidden={false}` if needed).
 * - Size with Tailwind classes (e.g. `className="h-5 w-5"`); the `1em`
 *   fallback keeps them sane even when no class is provided.
 * - `currentColor` lets icons inherit the surrounding text color.
 */
